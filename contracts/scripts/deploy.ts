import { ethers, artifacts, network } from "hardhat";
import * as fs from "fs";
import * as path from "path";

function setEnvVar(file: string, key: string, value: string) {
  let text = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const line = `${key}=${value}`;
  const re = new RegExp(`^${key}=.*$`, "m");
  text = re.test(text) ? text.replace(re, line) : text + (text.endsWith("\n") || !text ? "" : "\n") + line + "\n";
  fs.writeFileSync(file, text);
}

async function main() {
  const [deployer] = await ethers.getSigners();
  const balance = await ethers.provider.getBalance(deployer.address);
  console.log(`Network: ${network.name}`);
  console.log(`Deployer: ${deployer.address}`);
  console.log(`Balance: ${ethers.formatEther(balance)} ETH`);
  if (balance === 0n) throw new Error("Deployer has no ETH. Fund it from a Base Sepolia faucet first.");

  const poker = await ethers.deployContract("DecentralisedPoker");
  await poker.waitForDeployment();
  const address = await poker.getAddress();
  const receipt = await poker.deploymentTransaction()!.wait();
  const deployBlock = receipt!.blockNumber;
  console.log(`Deployed to ${address} at block ${deployBlock}`);

  const { abi } = await artifacts.readArtifact("DecentralisedPoker");
  const { chainId } = await ethers.provider.getNetwork();

  // shared file that web/ and server/ import
  const sharedFile = path.resolve(__dirname, "../../shared/contract.ts");
  const contents = `// AUTO-GENERATED by contracts/scripts/deploy.ts. Do not edit by hand.
export const POKER_ADDRESS = "${address}" as const;
export const POKER_CHAIN_ID = ${chainId};
export const POKER_DEPLOY_BLOCK = ${deployBlock};
export const POKER_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;
  fs.writeFileSync(sharedFile, contents);
  console.log(`Wrote ${sharedFile}`);

  // env files
  setEnvVar(path.resolve(__dirname, "../../web/.env"), "NEXT_PUBLIC_CONTRACT_ADDRESS", address);
  setEnvVar(path.resolve(__dirname, "../../server/.env"), "CONTRACT_ADDRESS", address);
  console.log("Updated web/.env and server/.env");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});